/** המשימה בנוסח של מי שמקבל אותה (p1/p2). */
export function missionFor(id, playerId) {
  const mission = secretMissions.find((m) => m.id === id);
  if (!mission) return null;
  return { ...mission, body: mission.body[playerId === 'p2' ? 'p2' : 'p1'] };
}
